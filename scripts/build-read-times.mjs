/**
 * Derive blog reading times from the actual article text.
 *
 *   npm run build && node scripts/build-read-times.mjs
 *
 * Writes data/blogReadTimes.ts (slug -> minutes) for the listing cards, and
 * rewrites the "N min read" literal inside each article component so the card
 * and the article can never disagree.
 *
 * The previous numbers were typed by hand and had drifted badly — 13 of 29 were
 * overstated by 2+ minutes. Deriving them keeps that from happening again.
 */
import fs from "node:fs";
import path from "node:path";

const WPM = 225; // typical silent-reading speed for web prose
const OUT = "out/blogs";
const DATA = "data/blogReadTimes.ts";
const ROUTE = "app/blogs/[slug]/page.tsx";

if (!fs.existsSync(OUT)) {
  console.error(`${OUT} not found — run the build first.`);
  process.exit(1);
}

// ---- slug -> component file, read from the route's BLOG_COMPONENTS map -----
const route = fs.readFileSync(ROUTE, "utf8");
const imports = new Map(); // component name -> file path
for (const m of route.matchAll(/import\s+(\w+)\s+from\s+["']@\/(components\/blogs\/[^"']+)["']/g)) {
  imports.set(m[1], `${m[2]}.tsx`);
}
const slugToFile = new Map();
for (const m of route.matchAll(/["']([a-z0-9-]+)["']\s*:\s*<(\w+)\s*\/>/g)) {
  const file = imports.get(m[2]);
  if (file && fs.existsSync(file)) slugToFile.set(m[1], file);
}

// ---- count the words Google (and a reader) actually sees ------------------
function wordsIn(html) {
  const text = html
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<nav[\s\S]*?<\/nav>/gi, " ")
    .replace(/<footer[\s\S]*?<\/footer>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/&[a-z#0-9]+;/gi, " ")
    .replace(/\s+/g, " ")
    .trim();
  return text ? text.split(" ").length : 0;
}

const readTimes = {};
for (const dir of fs.readdirSync(OUT, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  const file = path.join(OUT, dir.name, "index.html");
  if (!fs.existsSync(file)) continue;
  readTimes[dir.name] = Math.max(1, Math.round(wordsIn(fs.readFileSync(file, "utf8")) / WPM));
}

const slugs = Object.keys(readTimes).sort();

// ---- emit the shared map --------------------------------------------------
fs.writeFileSync(
  DATA,
  `// GENERATED by scripts/build-read-times.mjs — do not edit by hand.
// Reading time in minutes, derived from each article's word count at ${WPM} wpm.
// Re-run after adding or editing a post: node scripts/build-read-times.mjs

export const blogReadTimes: Record<string, number> = {
${slugs.map((s) => `  "${s}": ${readTimes[s]},`).join("\n")}
};

/** Minutes for a slug, or null when the post has no generated entry yet. */
export function readTimeFor(slug: string): number | null {
  return blogReadTimes[slug] ?? null;
}
`
);

// ---- keep each article's own byline honest --------------------------------
let rewritten = 0;
const unmatched = [];
for (const [slug, file] of slugToFile) {
  const minutes = readTimes[slug];
  if (!minutes) continue;
  const src = fs.readFileSync(file, "utf8");
  if (!/\d+\s*min read/.test(src)) {
    unmatched.push(`${slug} (no "min read" in ${file})`);
    continue;
  }
  const next = src.replace(/\d+\s*min read/g, `${minutes} min read`);
  if (next !== src) {
    fs.writeFileSync(file, next);
    rewritten++;
  }
}

console.log(`${slugs.length} articles -> ${DATA}`);
console.log(`article bylines rewritten: ${rewritten}`);
if (unmatched.length) console.log(`skipped: ${unmatched.join(", ")}`);
